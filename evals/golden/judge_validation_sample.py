"""
Judge Validation Sample — Synthetic Placeholder (H4)
=======================================================

Overview
--------
A synthetic stand-in for the 50-case judge-validation sample ``plan/product/human-tasks/H4-judge-
rubric.md`` asks two human raters to double-score, shaped exactly like the two sheets they will
return (``H4-case-sheet-Rater1.csv``, ``H4-case-sheet-Rater2.csv``), plus a synthetic stand-in for
the automated judge's own verdicts on the same 50 cases. H4 is not due until 2026-10-03/04; this
fixture exists so ``evals.judge_validation``'s agreement computation, and the report generator's
judge-validation section, are real, tested code today, not a stub waiting on the human sample to
find out whether they work.

Scope
-----
In: 50 synthetic, deterministic ``RaterScore``/``JudgeVerdict`` triples, case ids ``J-01``
through ``J-50`` matching ``H4-case-sheet.csv``'s own numbering, so the real returned sheets slot
into the same ``case_id`` space unchanged.
Out: real human judgment of any kind. Every score here is invented to exercise the agreement code
path, never to represent what a rater would actually say about a real conversation.

Design Principles
-----------------
- **Provenance is stated, never inferred**, the same rule ``evals.models.Case`` already applies to
  the golden set: ``PROVENANCE`` names this sample as ``"team_generated_synthetic"``, and the
  report generator refuses to present this sample's agreement numbers as the real ≥50-case human
  validation the plan requires unless the sample it is given carries a different provenance.
- **The sample exercises all three of this module's own decision branches, not just the happy
  path** (the same "a vacuous test looks identical until mutation-tested" discipline
  ``evals.judge_validation``'s own tests already apply):
  - ``grounding``: full three-way agreement on every case — the not-demoted path.
  - ``language_quality``: the two human raters agree with each other on every case, but the
    synthetic judge disagrees with both on 15 of 50 — below the 80% threshold, so this dimension
    is demoted. Demonstrates the demotion firing from a genuine judge/human split, not a
    data-entry mistake shared by all three sources.
  - ``clarification``: scored (never ``NA``) only on the 15 cases standing in for the golden set's
    ``ambiguous`` category, matching the real rubric's own scope for this dimension; full
    agreement on the scored subset, exercising the NA-exclusion path with a *defined* (not
    "not defined") outcome.
- **Generated by a small deterministic loop, not typed by hand.** Unlike an authored golden-set
  case (where every field is a specific reviewed choice), these 50 rows are mechanically identical
  placeholder data; a loop keeps that visible and keeps the deliberately-injected disagreement
  (case ids 36-50) as the one place a reader needs to look for what makes this fixture non-trivial.

Runtime Contract
-----------------
``PROVENANCE``: the literal ``"team_generated_synthetic"``.
``RATER_1_SCORES``, ``RATER_2_SCORES``: ``tuple[RaterScore, ...]``, 50 entries each.
``JUDGE_VERDICTS``: ``tuple[JudgeVerdict, ...]``, 50 entries.

Limitations
-----------
When the real returned sheets land, they replace this module's three tuples (built the same way
H4-case-sheet.csv's columns already name the fields); the agreement computation and the report
section need no change, only the data source and its provenance value.
"""

from __future__ import annotations

from typing import Literal

from evals.judge import JudgeVerdict
from evals.judge_validation import RaterScore

PROVENANCE: Literal["team_generated_synthetic"] = "team_generated_synthetic"

_SAMPLE_SIZE = 50
_JUDGE_MODEL = "claude-sonnet-5"
_PROMPT_VERSION = "1"

# Cases standing in for the golden set's `ambiguous` category: the only ones a clarification score
# applies to, matching the real rubric's own scope for that dimension.
_CLARIFICATION_APPLIES_UP_TO = 15

# The judge disagrees with both human raters on language_quality for these cases (case ids 36-50,
# 15 of 50 = 30%): below DEMOTION_THRESHOLD (80% agreement, i.e. more than 20% disagreement),
# demoting this dimension. Both raters still agree with each other on every case.
_JUDGE_LANGUAGE_QUALITY_DISAGREES_FROM = 36


def _case_id(number: int) -> str:
    return f"J-{number:02d}"


def _clarification_for(number: int) -> int | None:
    return 2 if number <= _CLARIFICATION_APPLIES_UP_TO else None


RATER_1_SCORES: tuple[RaterScore, ...] = tuple(
    RaterScore(
        case_id=_case_id(number),
        role="Rater 1",
        grounding=2,
        language_quality=2,
        clarification=_clarification_for(number),
    )
    for number in range(1, _SAMPLE_SIZE + 1)
)

RATER_2_SCORES: tuple[RaterScore, ...] = tuple(
    RaterScore(
        case_id=_case_id(number),
        role="Rater 2",
        grounding=2,
        language_quality=2,
        clarification=_clarification_for(number),
    )
    for number in range(1, _SAMPLE_SIZE + 1)
)

JUDGE_VERDICTS: tuple[JudgeVerdict, ...] = tuple(
    JudgeVerdict(
        case_id=_case_id(number),
        grounding=2,
        language_quality=1 if number >= _JUDGE_LANGUAGE_QUALITY_DISAGREES_FROM else 2,
        clarification=_clarification_for(number),
        rationale="Synthetic placeholder verdict (team_generated_synthetic); not a real judgment.",
        judge_model=_JUDGE_MODEL,
        prompt_version=_PROMPT_VERSION,
    )
    for number in range(1, _SAMPLE_SIZE + 1)
)
