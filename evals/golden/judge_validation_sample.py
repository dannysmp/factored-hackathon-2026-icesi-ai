"""
Judge Validation Sample
=======================

Overview
--------
A synthetic stand-in for the 50-case judge-validation sample that two human raters double-score,
shaped like the two sheets they return (``H4-case-sheet-Rater1.csv`` and
``H4-case-sheet-Rater2.csv``), plus synthetic verdicts from the automated judge on the same 50
cases. It lets ``evals.judge_validation``'s agreement computation and the report's judge-validation
section run as real, tested code before the human sample exists.

Scope
-----
In: 50 deterministic ``RaterScore`` and ``JudgeVerdict`` records per source, with case ids ``J-01``
through ``J-50`` so that returned sheets, which use the same numbering, slot into the same
``case_id`` space unchanged.
Out: real human judgment of any kind. Every score is invented to exercise the agreement code path
and does not represent what a rater would say about a real conversation.

Design Principles
-----------------
- **Provenance is stated, never inferred**, as for ``evals.models.Case``: ``PROVENANCE`` names the
  sample ``"team_generated_synthetic"``, and the report generator withholds agreement numbers from
  any sample whose provenance is not ``"human"``.
- **The sample exercises every decision branch, not only the happy path:**
  - ``grounding``: full three-way agreement on every case, so the dimension is not demoted.
  - ``language_quality``: the two raters agree with each other on every case, but the judge
    disagrees with both on 15 of 50 (agreement 70%, below the 80% threshold), so the dimension is
    demoted by a genuine judge-versus-human split rather than by an error shared by all three.
  - ``clarification``: scored (never ``NA``) only on the first 15 cases, which stand in for the
    golden set's ``ambiguous`` category, as in the rubric; full agreement on that subset
    exercises the NA-exclusion path with a defined outcome.
- **Generated by a loop, not typed by hand.** The rows are mechanically identical, so a loop keeps
  that visible and leaves the injected disagreement (case ids 36 to 50) as the one thing to look
  for.

Runtime Contract
-----------------
``PROVENANCE``: the literal ``"team_generated_synthetic"``.
``RATER_1_SCORES``, ``RATER_2_SCORES``: ``tuple[RaterScore, ...]``, 50 entries each.
``JUDGE_VERDICTS``: ``tuple[JudgeVerdict, ...]``, 50 entries.

Limitations
-----------
Returned human sheets replace the three tuples; the agreement computation and the report section
need no change, only the data source and its provenance value.
"""

from __future__ import annotations

from typing import Literal

from evals.judge import JudgeVerdict
from evals.judge_validation import RaterScore

#: Provenance label of this sample; the report withholds its agreement numbers as non-human.
PROVENANCE: Literal["team_generated_synthetic"] = "team_generated_synthetic"

# Number of cases in the sample, and the judge identity recorded on every synthetic verdict.
_SAMPLE_SIZE = 50
_JUDGE_MODEL = "claude-sonnet-5"
_PROMPT_VERSION = "1"

# Cases standing in for the golden set's `ambiguous` category: the only ones a clarification score
# applies to, matching the real rubric's own scope for that dimension.
_CLARIFICATION_APPLIES_UP_TO = 15

# The judge disagrees with both human raters on language_quality for these cases (case ids 36-50,
# 15 of 50 = 30%): below DEMOTION_THRESHOLD (80% agreement, i.e. more than 20% disagreement),
# demoting this dimension. Both raters still agree with each other on every case.
_JUDGE_LANGUAGE_QUALITY_DISAGREES_FROM = 36


def _case_id(number: int) -> str:
    """The sample case id for ``number``, zero-padded to two digits (``J-01``)."""
    return f"J-{number:02d}"


def _clarification_for(number: int) -> int | None:
    """The clarification score for case ``number``: 2 on the ambiguous stand-ins, else ``None``."""
    return 2 if number <= _CLARIFICATION_APPLIES_UP_TO else None


RATER_1_SCORES: tuple[RaterScore, ...] = tuple(
    RaterScore(
        case_id=_case_id(number),
        role="Rater 1",
        grounding=2,
        language_quality=2,
        clarification=_clarification_for(number),
    )
    for number in range(1, _SAMPLE_SIZE + 1)
)

RATER_2_SCORES: tuple[RaterScore, ...] = tuple(
    RaterScore(
        case_id=_case_id(number),
        role="Rater 2",
        grounding=2,
        language_quality=2,
        clarification=_clarification_for(number),
    )
    for number in range(1, _SAMPLE_SIZE + 1)
)

JUDGE_VERDICTS: tuple[JudgeVerdict, ...] = tuple(
    JudgeVerdict(
        case_id=_case_id(number),
        grounding=2,
        language_quality=1 if number >= _JUDGE_LANGUAGE_QUALITY_DISAGREES_FROM else 2,
        clarification=_clarification_for(number),
        rationale="Synthetic placeholder verdict (team_generated_synthetic); not a real judgment.",
        judge_model=_JUDGE_MODEL,
        prompt_version=_PROMPT_VERSION,
    )
    for number in range(1, _SAMPLE_SIZE + 1)
)
